# Pre-build step (design D7): gzips web/index.html into include/generated/web_index.h, so the settings page
# is compiled into the firmware and no filesystem image has to be uploaded. Runs before every ESP32 build
# (extra_scripts in platformio.ini); the header is git-ignored.
Import("env")  # noqa: F821 - provided by PlatformIO

import gzip
import os

project = env.subst("$PROJECT_DIR")  # noqa: F821
source = os.path.join(project, "web", "index.html")
target_dir = os.path.join(project, "include", "generated")
target = os.path.join(target_dir, "web_index.h")


def render_header(html):
    # mtime=0 makes the output depend on the HTML alone, so an unchanged page does not cause a rebuild.
    packed = gzip.compress(html, compresslevel=9, mtime=0)
    rows = []
    for i in range(0, len(packed), 16):
        rows.append("  " + ", ".join("0x%02x" % b for b in packed[i : i + 16]) + ",")
    header = (
        "// Generated by scripts/embed_web.py from web/index.html. Do not edit: change the HTML and rebuild.\n"
        "#pragma once\n"
        "\n"
        "#include <stdint.h>\n"
        "\n"
        "// %d bytes of HTML, %d bytes gzipped.\n"
        "static const uint8_t kWebIndexGz[] = {\n"
        "%s\n"
        "};\n" % (len(html), len(packed), "\n".join(rows))
    )
    return header, len(packed)


def main():
    with open(source, "rb") as f:
        html = f.read()
    header, packed_size = render_header(html)

    current = None
    if os.path.exists(target):
        with open(target, "r", encoding="ascii") as f:
            current = f.read()
    if current == header:
        return

    os.makedirs(target_dir, exist_ok=True)
    with open(target, "w", encoding="ascii", newline="\n") as f:
        f.write(header)
    print("embed_web: %s -> %s (%d bytes gzipped)" % (os.path.relpath(source, project), os.path.relpath(target, project), packed_size))


main()
